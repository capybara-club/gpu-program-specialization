        }
        if (lane == 0u) {
            atomicAdd(output_sse + (size_t)0 * output_leading_dimension + 1u, block_sse_000_001);
        }
        float block_sse_001_000 = lane < num_waves ? partial_sse[(size_t)2 * 16u + lane] : 0.0f;
        for (unsigned int delta = warpSize / 2u; delta != 0u; delta >>= 1u) {
            block_sse_001_000 += __shfl_down(block_sse_001_000, delta, warpSize);
        }
        if (lane == 0u) {
