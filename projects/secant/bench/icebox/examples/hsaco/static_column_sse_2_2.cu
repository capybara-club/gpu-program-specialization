    for (unsigned int delta = warpSize / 2u; delta != 0u; delta >>= 1u) {
        sse_001_001 += __shfl_down(sse_001_001, delta, warpSize);
    }
    if (lane == 0u) {
        partial_sse[(size_t)3 * 16u + wave] = sse_001_001;
    }

    __syncthreads();
    if (wave == 0u) {
        float block_sse_000_000 = lane < num_waves ? partial_sse[(size_t)0 * 16u + lane] : 0.0f;
        for (unsigned int delta = warpSize / 2u; delta != 0u; delta >>= 1u) {
            block_sse_000_000 += __shfl_down(block_sse_000_000, delta, warpSize);
        }
        if (lane == 0u) {
            atomicAdd(output_sse + (size_t)0 * output_leading_dimension + 0u, block_sse_000_000);
        }
        float block_sse_000_001 = lane < num_waves ? partial_sse[(size_t)1 * 16u + lane] : 0.0f;
