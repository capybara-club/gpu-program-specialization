}

extern "C" __global__
void secant_hsaco_sse_compact(
    const float* __restrict__ padded_sse,
    size_t padded_leading_dimension,
    float* __restrict__ output_sse,
    size_t output_leading_dimension
) {
    const size_t result = (size_t)blockIdx.x * blockDim.x + threadIdx.x;
    if (result < 8u) {
        const size_t series = result / 2u;
        const size_t target = result % 2u;
        output_sse[series * output_leading_dimension + target] = padded_sse[series * padded_leading_dimension + target];
    }
}
